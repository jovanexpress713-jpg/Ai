import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const server = read('server.ts');
const auth = read('server/auth.ts');
const workspace = read('server/workspace-fs.ts');
const agent = read('server/agent.ts');
const sandbox = read('server/sandbox.ts');
const compose = read('docker-compose.yml');
const ci = read('.github/workflows/ci.yml');
const failures = [];
function assert(name, condition) { if (!condition) failures.push(name); }
assert('authentication middleware is installed', server.includes("app.use('/api', sameOriginForStateChange, requireAuth)"));
assert('production login requires strong secret', auth.includes('configuredPassword.length < 16'));
assert('login timing-safe comparison', auth.includes('crypto.timingSafeEqual'));
assert('login rate limiting exists', auth.includes('MAX_ATTEMPTS') && auth.includes('BLOCK_MS'));
assert('role switching disabled in production', server.includes("process.env.NODE_ENV === 'production' || !perm.allowed || user?.role !== 'Owner'"));
assert('path traversal boundary check exists', workspace.includes('escapes workspace root'));
assert('symlink escape check exists', workspace.includes('Symlink/path resolves outside workspace'));
assert('environment secret files are blocked', workspace.includes('.env.'));
assert('terminal shell composition is blocked', server.includes('/[;&|`$(){}<>\\n\\r]/'));
assert('destructive git operations are blocked', server.includes('git\\s+(reset|clean|checkout|restore|rebase|push|commit|merge|cherry-pick)'));
assert('production terminal uses sandbox adapter', server.includes('executeSandboxCommand') && server.includes('sandboxRequired'));
assert('sandbox uses namespace isolation', sandbox.includes('--unshare-all'));
assert('agent verifies proposed changes before live apply', agent.includes('verifyProposedChanges(task.proposedChanges'));
assert('agent runs lint, tests, and build', agent.includes("['npm run lint', 'npm run test', 'npm run build']"));
assert('failed autonomous verification leaves workspace untouched', agent.includes('workspace unchanged'));
assert('GitHub endpoints enforce RBAC', server.includes('ROLE_ACTIONS.GITHUB'));
assert('Gemini diagnostics enforce RBAC', server.includes('ROLE_ACTIONS.GEMINI_TEST'));
assert('task rejection enforces RBAC', server.includes('ROLE_ACTIONS.REJECT_TASK'));
assert('docker socket is not mounted', !compose.includes('/var/run/docker.sock'));
assert('CI does not require an absent lockfile', ci.includes('npm install'));
assert('proposed patch rejects traversal and symlink escapes', sandbox.includes('Unsafe proposed path') && sandbox.includes('realpathSync'));
assert('protected infrastructure cannot be auto-applied', ['package.json','package-lock.json','Dockerfile','docker-compose.yml','vite.config.ts','tsconfig.json'].every((f) => sandbox.includes(f)) && sandbox.includes('Protected infrastructure file'));
assert('agent does not execute host shell directly', !agent.includes('node:child_process') && !agent.includes('promisify(exec)'));
assert('sandbox does not expose host /etc', !sandbox.includes("'--ro-bind', '/etc', '/etc'"));
assert('production startup requires bubblewrap', server.includes('bubblewrap is required for isolated execution'));
assert('password error matches 16-char policy', server.includes('at least 16 characters'));
assert('direct dependency versions are pinned', !read('package.json').includes('\"^'));
assert('database persistence uses atomic rename', read('server/db.ts').includes('renameSync(tmpPath, DB_PATH)'));
assert('deployment health reports actual provider state', server.includes('deploymentStatus()'));
assert('deployment adapter exists', fs.existsSync(path.join(root, 'server/deployment.ts')));
assert('production Docker definition exists', fs.existsSync(path.join(root, 'Dockerfile')));
if (failures.length) {
  console.error('Security verification failed:');
  for (const f of failures) console.error(` - ${f}`);
  process.exit(1);
}
console.log('FORGEX security verification: PASS');
